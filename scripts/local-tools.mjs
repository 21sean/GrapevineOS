import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseEnv } from "node:util";

export const root = fileURLToPath(new URL("../", import.meta.url));
export const cli = path.join(root, "node_modules/supabase/dist/supabase.js");

export function readEnv(file) {
  return existsSync(file) ? parseEnv(readFileSync(file, "utf8")) : {};
}

export function isLocalUrl(value) {
  try {
    const url = new URL(value);
    return (
      ["http:", "https:"].includes(url.protocol) &&
      ["localhost", "127.0.0.1", "[::1]"].includes(url.hostname) &&
      !url.username &&
      !url.password
    );
  } catch {
    return false;
  }
}

export function assertLocal(value) {
  if (!isLocalUrl(value)) throw new Error("This command requires a localhost Supabase URL.");
}

export function runNode(args, options = {}) {
  return execFileSync(process.execPath, args, {
    cwd: root,
    stdio: "inherit",
    windowsHide: true,
    ...options,
  });
}

export function supabase(args, options = {}) {
  try {
    return runNode([cli, ...args], options);
  } catch (error) {
    // execFileSync's message can contain captured credentials from CLI stdout.
    throw new Error(
      `Supabase ${args[0]} failed (exit ${error.status ?? "unknown"}). Check the CLI diagnostics above.`,
    );
  }
}

// Only managed local credentials are replaced; user settings and comments survive.
export function mergeEnv(text, values, replace = []) {
  const current = parseEnv(text);
  let result = text;
  for (const [key, value] of Object.entries(values)) {
    if (Object.hasOwn(current, key) && !replace.includes(key)) continue;
    if (/[\r\n]/.test(value)) throw new Error(`Invalid multiline value for ${key}`);
    const line = `${key}=${JSON.stringify(value)}`;
    const pattern = new RegExp(`^[\\t ]*(?:export\\s+)?${key}\\s*=.*$`, "gm");
    result = pattern.test(result)
      ? result.replace(pattern, () => line)
      : `${result.trimEnd()}\n${line}\n`;
  }
  return result;
}

export function writeEnv(file, values, replace = []) {
  const text = existsSync(file) ? readFileSync(file, "utf8") : "# Generated by npm run setup.\n";
  const next = mergeEnv(text, values, replace);
  if (next !== text) writeFileSync(file, next, { mode: 0o600 });
}
