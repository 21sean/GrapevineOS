/**
 * Regenerate src/db-types.ts from the Supabase project the server points at.
 *
 * A local URL uses the local stack. Hosted URLs use their project ref and need
 * `npx supabase login` or SUPABASE_ACCESS_TOKEN. Both use the pinned CLI.
 *
 *   npm run db:types
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { isLocalUrl, supabase } from "../../scripts/local-tools.mjs";

const here = (rel) => fileURLToPath(new URL(rel, import.meta.url));

function envValue(key) {
  if (process.env[key]) return process.env[key];
  let text;
  try {
    text = readFileSync(here("../.env"), "utf8");
  } catch {
    return undefined;
  }
  const line = text.split(/\r?\n/).find((l) => l.startsWith(`${key}=`));
  return line
    ?.slice(key.length + 1)
    .trim()
    .replace(/^["']|["']$/g, "");
}

const url = envValue("SUPABASE_URL");
const ref = url?.match(/^https:\/\/([a-z0-9]+)\.supabase\.co\/?$/)?.[1];
const local = isLocalUrl(url);
if (!local && !ref) {
  console.error("SUPABASE_URL must be a local URL or a hosted *.supabase.co project");
  process.exit(1);
}

let types;
try {
  types = supabase(
    ["gen", "types", "typescript", "--schema", "public", ...(local ? [] : [`--remote=${ref}`])],
    { encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] },
  ).trimStart();
} catch (err) {
  console.error(String(err.stdout ?? err.message).slice(0, 400));
  console.error("\nStart local Supabase, or run `npx supabase login` for a hosted project.");
  process.exit(1);
}
if (!types.startsWith("export type Json")) {
  console.error(types.slice(0, 400));
  process.exit(1);
}

const header =
  "// Generated by `npm run db:types` (scripts/db-types.mjs) from the linked\n" +
  "// Supabase project. Do not edit by hand: change a migration and regenerate.\n";
writeFileSync(here("../src/db-types.ts"), header + types);
console.log(
  `wrote src/db-types.ts for ${local ? "local Supabase" : `project ${ref}`} (${types.split("\n").length} lines)`,
);
