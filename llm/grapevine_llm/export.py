"""Deterministic JSON Schema and Zod views of the Pydantic contracts."""
import argparse
import json
from pathlib import Path

from jsonschema import Draft202012Validator

from .contracts import OUTPUTS, TOOL_ARGS, VERSION, Context
from .evals import GoldenCase, Report
from .pins import ModelManifest
from .client import Request, ResultEnvelope

ROOT = Path(__file__).resolve().parents[2]
SCHEMAS = ROOT / "contracts" / "llm" / VERSION
GENERATED = ROOT / "server" / "src" / "llm" / "generated.ts"


def zod(s: dict, defs: dict) -> str:
    if "$ref" in s:
        return zod(defs[s["$ref"].split("/")[-1]], defs)
    if "const" in s:
        return f"z.literal({json.dumps(s['const'])})"
    if "enum" in s:
        return f"z.enum({json.dumps(s['enum'])})"
    alternatives = s.get("anyOf", s.get("oneOf"))
    if alternatives and len(alternatives) == 2 and alternatives[-1].get("type") == "null":
        return zod(alternatives[0], defs) + ".nullable()"
    if alternatives:
        return "z.union([" + ",".join(zod(a, defs) for a in alternatives) + "])"
    kind = s.get("type")
    if kind == "object":
        required = s.get("required", [])
        fields = []
        for key, value in s.get("properties", {}).items():
            expr = zod(value, defs)
            if key not in required:
                expr += ".optional()"
            fields.append(f"{json.dumps(key)}:{expr}")
        return "z.object({" + ",".join(fields) + "}).strict()"
    if kind == "array":
        if "prefixItems" in s:
            return "z.tuple([" + ",".join(zod(a, defs) for a in s["prefixItems"]) + "])"
        expr = f"z.array({zod(s['items'], defs)})"
        keys = [("minItems", "min"), ("maxItems", "max")]
    elif kind in ("number", "integer"):
        expr = "z.number()" + (".int()" if kind == "integer" else "")
        keys = [("minimum", "min"), ("maximum", "max"), ("exclusiveMinimum", "gt"), ("exclusiveMaximum", "lt")]
    elif kind == "string":
        expr = "z.string()"
        if "pattern" in s:
            expr += f".regex(new RegExp({json.dumps(s['pattern'])}))"
        keys = [("minLength", "min"), ("maxLength", "max")]
    elif kind in ("boolean", "null"):
        return f"z.{kind}()"
    else:
        raise ValueError(f"unsupported JSON Schema node: {s}")
    for key, method in keys:
        if key in s:
            expr += f".{method}({s[key]})"
    return expr


def artifacts() -> dict[Path, str]:
    result = {}
    lines = ['// Generated by python -m grapevine_llm.export. Do not edit.', 'import { z } from "zod";', f'export const CONTRACT_VERSION = "{VERSION}";']
    models = {**OUTPUTS, **{f"tool_{k}": v for k, v in TOOL_ARGS.items()}, "context": Context,
              "golden": GoldenCase, "eval_report": Report, "model_manifest": ModelManifest, "request": Request, "result_envelope": ResultEnvelope}
    for name, model in models.items():
        schema = model.model_json_schema(by_alias=True)
        schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
        schema["$id"] = f"urn:grapevine:llm:{VERSION}:{name}"
        Draft202012Validator.check_schema(schema)
        result[SCHEMAS / f"{name}.json"] = json.dumps(schema, indent=2, sort_keys=True) + "\n"
        lines.append(f"export const {name}Schema = {zod(schema, schema.get('$defs', {}))};")
    lines.append("export const outputSchemas = {" + ",".join(f"{k}:{k}Schema" for k in OUTPUTS) + "};")
    lines.append("export const toolSchemas = {" + ",".join(f"{k}:tool_{k}Schema" for k in TOOL_ARGS) + "};")
    lines.append("export type Task = keyof typeof outputSchemas;")
    lines.append("export type Output<T extends Task> = z.infer<(typeof outputSchemas)[T]>;")
    lines.append("export type ValidationContext = z.input<typeof contextSchema>;")
    result[GENERATED] = "\n".join(lines) + "\n"
    return result


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, expected in artifacts().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != expected:
                raise SystemExit(f"stale generated contract: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
